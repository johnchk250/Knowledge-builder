"""Apply a canonical CHP model delta to the canonical plant model.

Supports schema_version 1 deltas with:
- new_documents (auto-ingested into documents & evidence before proposals run)
- id_resolution_map (auto-resolves random UUIDs generated by earlier local delta runs)
- automatic rehearsal when --apply is invoked directly

Modes:
    --check      validate only (no live database change)
    --rehearse   apply the whole delta onto a throwaway copy of the live DB
    --apply      guarded live acceptance (auto-runs --rehearse if needed)
"""
import argparse
import hashlib
import json
import re
import shutil
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from chp.patches import validate, commit
from chp.reviewed_ingestion import stage
from chp.store import Store, normalize


def find_quote(text, quote):
    if not quote:
        return None
    if quote in text:
        return quote
    pattern = re.sub(r'\s+', r'\\s+', re.escape(quote.strip()))
    if not pattern.strip():
        return None
    match = re.search(pattern, text)
    return match.group(0) if match else None


def load_delta(path):
    raw = Path(path).read_text(encoding='utf-8')
    delta = json.loads(raw)
    if delta.get('schema_version') != 1 or not isinstance(delta.get('proposals'), list):
        raise ValueError('Unsupported delta file: expected schema_version 1 and a proposals array')
    return delta, hashlib.sha256(raw.encode('utf-8')).hexdigest()


def doc_evidence(store, doc):
    return {e['id']: e for e in store.rows('SELECT * FROM evidence WHERE document_id=?', (doc,))}


def body_size(proposal):
    return len(json.dumps({'summary': proposal.get('summary', ''), 'operations': proposal.get('operations') or []}))


def resolve_dynamic_ids(store, delta, proposal, repairs):
    """Resolve entity and assertion UUIDs that differ across local delta applications."""
    id_map = delta.get('id_resolution_map') or {}
    ent_hints = id_map.get('entities') or {}
    fact_hints = id_map.get('assertions') or {}

    model = store.model()
    entities_by_id = {e['id']: e for e in model['entities'] if not e.get('inactive')}
    label_to_id = {}
    norm_to_id = {}
    for e in model['entities']:
        if e.get('inactive'):
            continue
        cid = e.get('canonical_id') or e['id']
        label_to_id[e['label']] = cid
        norm_to_id[normalize(e['label'])] = cid
    for a in model['aliases']:
        if a.get('retracted'):
            continue
        ent = entities_by_id.get(a['entity_id'])
        if ent and not ent.get('inactive'):
            cid = ent.get('canonical_id') or ent['id']
            norm_to_id.setdefault(a['normalized'], cid)

    def resolve_ent(eid):
        if not eid or not isinstance(eid, str) or eid.startswith('tmp_'):
            return eid
        if eid in entities_by_id:
            return entities_by_id[eid].get('canonical_id') or eid
        hint = ent_hints.get(eid)
        if hint:
            lbl = hint.get('label')
            if lbl in label_to_id:
                return label_to_id[lbl]
            if lbl and normalize(lbl) in norm_to_id:
                return norm_to_id[normalize(lbl)]
        return eid

    active_assertions = {a['id']: a for a in model['assertions'] if not a.get('retirement')}
    raw_assertions = {r['id']: r for r in store.rows('SELECT * FROM assertions')}
    retired_set = {r['assertion_id'] for r in store.rows('SELECT assertion_id FROM retirements')}
    used_assertions = set()

    def resolve_fact(aid):
        if not aid or not isinstance(aid, str):
            return aid
        if aid in active_assertions and aid not in retired_set and aid not in used_assertions:
            return aid
        hint = fact_hints.get(aid)
        if not hint:
            return None
        subj = resolve_ent(hint.get('subject'))
        if subj not in entities_by_id and hint.get('subject_label'):
            subj = label_to_id.get(hint['subject_label']) or norm_to_id.get(normalize(hint['subject_label'])) or subj
        obj = resolve_ent(hint.get('object_entity')) if hint.get('object_entity') else None
        if obj and obj not in entities_by_id and hint.get('object_label'):
            obj = label_to_id.get(hint['object_label']) or norm_to_id.get(normalize(hint['object_label'])) or obj
        pred = hint.get('predicate')
        val = hint.get('value')
        unit = hint.get('unit')

        # 1. Exact match on (subject, predicate, raw_value, object_entity, unit)
        for cand_id, r in raw_assertions.items():
            if cand_id in retired_set or cand_id in used_assertions or cand_id not in active_assertions:
                continue
            if r['subject'] == subj and r['predicate'] == pred and r['value'] == val and r['object_entity'] == obj and r['unit'] == unit:
                return cand_id

        # 2. Match ignoring unit formatting differences
        for cand_id, r in raw_assertions.items():
            if cand_id in retired_set or cand_id in used_assertions or cand_id not in active_assertions:
                continue
            if r['subject'] == subj and r['predicate'] == pred and r['value'] == val and r['object_entity'] == obj:
                return cand_id

        # 3. Single active assertion on (subject, predicate) for scalar property
        if obj is None:
            cands = [
                cand_id for cand_id, r in raw_assertions.items()
                if cand_id not in retired_set and cand_id not in used_assertions and cand_id in active_assertions
                and r['subject'] == subj and r['predicate'] == pred
            ]
            if len(cands) == 1:
                return cands[0]
        return None

    filtered_ops = []
    doc = proposal.get('document', '')
    for i, op in enumerate(proposal.get('operations') or []):
        for k in ('subject', 'object_entity', 'entity', 'source', 'target'):
            if k in op and op[k]:
                new_eid = resolve_ent(op[k])
                if new_eid != op[k]:
                    repairs.append({'document': doc, 'op': i + 1, 'kind': 'entity_id', 'from': op[k], 'to': new_eid})
                    op[k] = new_eid
        if op.get('op') == 'merge' and (op.get('source') == op.get('target') or op.get('source') not in entities_by_id):
            repairs.append({'document': doc, 'op': i + 1, 'kind': 'skip_already_merged', 'from': op.get('source'), 'to': op.get('target')})
            continue
        if 'assertion_id' in op and op['assertion_id']:
            old_aid = op['assertion_id']
            new_aid = resolve_fact(old_aid)
            if new_aid:
                if new_aid != old_aid:
                    repairs.append({'document': doc, 'op': i + 1, 'kind': 'assertion_id', 'from': old_aid, 'to': new_aid})
                    op['assertion_id'] = new_aid
                used_assertions.add(new_aid)
                filtered_ops.append(op)
            else:
                if op.get('op') == 'retire':
                    repairs.append({'document': doc, 'op': i + 1, 'kind': 'skip_already_retired', 'from': old_aid, 'to': None})
                    continue
                elif op.get('op') == 'supersede':
                    # Convert to assert if target assertion is already retired or absent
                    op = dict(op)
                    op['op'] = 'assert'
                    op.pop('assertion_id', None)
                    op.pop('reason', None)
                    repairs.append({'document': doc, 'op': i + 1, 'kind': 'supersede_to_assert', 'from': old_aid, 'to': 'assert'})
                    filtered_ops.append(op)
                elif op.get('op') == 'qualify':
                    repairs.append({'document': doc, 'op': i + 1, 'kind': 'skip_missing_qualify', 'from': old_aid, 'to': None})
                    continue
                else:
                    filtered_ops.append(op)
        else:
            filtered_ops.append(op)
    proposal['operations'] = filtered_ops


def resolve_supports(store, proposal, repairs, problems):
    doc = proposal['document']
    ev = doc_evidence(store, doc)
    if not ev:
        problems.append('%s: document has no evidence blocks in the canonical DB' % doc)
    visual = set()
    for i, op in enumerate(proposal['operations']):
        supports = op.get('evidence')
        if not isinstance(supports, list):
            continue
        kept = []
        for j, support in enumerate(supports):
            label = 'op %d.%d' % (i + 1, j + 1)
            if not isinstance(support, dict):
                problems.append('%s: evidence support is not an object' % label)
                continue
            eid = support.get('evidence_id')
            quote = support.get('quote', '') or ''
            region = support.get('region')
            page = support.get('page')
            if not eid and page is not None:
                page_evs = [e for e in ev.values() if str(e['page']) == str(page)]
                if quote:
                    for e in page_evs:
                        fixed = find_quote(e['text'] or '', quote)
                        if fixed:
                            eid, quote = e['id'], fixed
                            break
                    if not eid:
                        problems.append('%s: quote not found on page %s of %s' % (label, page, doc))
                        continue
                elif region is not None:
                    imgs = [e for e in page_evs if e['image']]
                    if not imgs:
                        problems.append('%s: no rendered page image for page %s of %s' % (label, page, doc))
                        continue
                    eid = imgs[0]['id']
                else:
                    problems.append('%s: page reference needs quote or region' % label)
                    continue
            if not eid or eid not in ev:
                problems.append('%s: evidence %s does not belong to %s' % (label, eid, doc))
                continue
            block = ev[eid]
            if quote:
                fixed = find_quote(block['text'] or '', quote)
                if not fixed:
                    problems.append('%s: quote not found in %s (evidence %s, page %s)' % (label, doc, eid, block['page']))
                    continue
                if fixed != quote:
                    repairs.append({'document': doc, 'op': i + 1, 'evidence_id': eid, 'from': quote, 'to': fixed})
                quote = fixed
            if not quote and region is None:
                problems.append('%s: support needs an exact quote or a visual region' % label)
                continue
            if region is not None:
                if not block['image']:
                    problems.append('%s: region support needs a rendered page image (evidence %s)' % (label, eid))
                    continue
                visual.add(eid)
            clean = {'evidence_id': eid, 'quote': quote}
            if region is not None:
                clean['region'] = region
            kept.append(clean)
        op['evidence'] = kept
    return sorted(visual)


def build_body(proposal, evidence_ids):
    ops = proposal['operations']
    route = proposal.get('route')
    if not route:
        route = 'reference' if ops and all(o.get('op') == 'source_note' for o in ops) else 'mixed'
    depth = ', '.join(proposal.get('depth_ids') or []) or 'the depth item'
    questions = proposal.get('questions') or []
    if ops and not questions:
        questions = ['What does this source establish for %s?' % depth]
    assessment = {'route': route,
                  'purpose': proposal.get('purpose') or proposal['summary'],
                  'questions': questions,
                  'gaps': proposal.get('gaps') or [],
                  'reviewed_evidence_ids': sorted(evidence_ids)}
    return {'summary': proposal['summary'], 'operations': ops, 'intake_assessment': assessment}


def copy_live(live_dir, target_dir):
    if target_dir.exists():
        shutil.rmtree(target_dir)
    target_dir.mkdir(parents=True)
    src_db = live_dir / 'plant.sqlite3'
    dst_db = target_dir / 'plant.sqlite3'
    shutil.copy2(src_db, dst_db)
    import os; os.utime(dst_db, None)
    for ext in ('-wal', '-shm'):
        w = live_dir / ('plant.sqlite3' + ext)
        if w.exists():
            shutil.copy2(w, target_dir / ('plant.sqlite3' + ext))


def ensure_new_documents(delta, store, delta_path=None, copy_files=False):
    new_docs = delta.get('new_documents') or []
    if not new_docs:
        return
    from chp.store import dumps as chp_dumps
    with store.transaction() as db:
        for nd in new_docs:
            doc_id = nd['id']
            exists = store.rows('SELECT id FROM documents WHERE id=?', (doc_id,), db)
            if not exists:
                db.execute(
                    'INSERT INTO documents VALUES(?,?,?,?,?,?,?,?,?)',
                    (
                        nd['id'],
                        nd['sha256'],
                        nd['name'],
                        nd.get('media_type', 'application/pdf'),
                        nd.get('revision', ''),
                        nd.get('authority', 'Approved Vendor SLD'),
                        nd['added'],
                        nd['size'],
                        chp_dumps(nd.get('warnings') or []),
                    ),
                )
            for ev in nd.get('evidence') or []:
                ev_exists = store.rows('SELECT id FROM evidence WHERE id=?', (ev['id'],), db)
                if not ev_exists:
                    meta = ev.get('metadata') if isinstance(ev.get('metadata'), dict) else json.loads(ev.get('metadata') or '{}')
                    digest = ev.get('sha256') or hashlib.sha256(
                        chp_dumps([ev['text'], ev['page'], ev['locator'], ev.get('image'), meta]).encode()
                    ).hexdigest()
                    db.execute(
                        'INSERT INTO evidence VALUES(?,?,?,?,?,?,?,?)',
                        (
                            ev['id'],
                            doc_id,
                            ev['page'],
                            ev['locator'],
                            ev['text'],
                            ev.get('image'),
                            digest,
                            chp_dumps(meta),
                        ),
                    )
    if copy_files and delta_path is not None:
        base_dir = Path(delta_path).resolve().parent
        for cand_orig in [base_dir / 'originals', base_dir / 'data/plant/originals', base_dir.parent / 'data/plant/originals']:
            if cand_orig.exists():
                dst_orig = store.root / 'originals'
                dst_orig.mkdir(parents=True, exist_ok=True)
                for nd in new_docs:
                    for sha_key in filter(None, [nd.get('sha256'), nd.get('drive_sha256')]):
                        for suffix in ('', '.pdf'):
                            src_f = cand_orig / (sha_key + suffix)
                            dst_f = dst_orig / (sha_key + suffix)
                            if src_f.exists() and not dst_f.exists():
                                shutil.copy2(src_f, dst_f)
        for cand_rend in [base_dir / 'renders', base_dir / 'data/plant/renders', base_dir.parent / 'data/plant/renders']:
            if cand_rend.exists():
                dst_rend = store.root / 'renders'
                dst_rend.mkdir(parents=True, exist_ok=True)
                for nd in new_docs:
                    for ev in nd.get('evidence') or []:
                        img_name = ev.get('image')
                        if img_name:
                            src_r = cand_rend / img_name
                            dst_r = dst_rend / img_name
                            if src_r.exists() and not dst_r.exists():
                                shutil.copy2(src_r, dst_r)
        for cand_dist in [base_dir / 'dist', base_dir, base_dir.parent / 'dist']:
            if cand_dist.exists():
                dst_dist = store.root.parent.parent / 'dist'
                if dst_dist.exists():
                    for js_name in ('plant-scene.js', 'plant-scene-model.js', 'plant-model.js', 'plant-explorer.js', 'plant-scene.css'):
                        src_js = cand_dist / js_name
                        dst_js = dst_dist / js_name
                        if src_js.exists() and src_js.resolve() != dst_js.resolve():
                            shutil.copy2(src_js, dst_js)


def process(delta, store, out_dir, commit_changes, delta_path=None):
    import copy
    delta = copy.deepcopy(delta)
    store._batch_shadow = True
    ensure_new_documents(delta, store, delta_path=delta_path, copy_files=commit_changes)
    base = delta['base_version']
    curr_v = store.version()
    if curr_v > base and curr_v < base + len(delta['proposals']):
        skip_n = curr_v - base
        delta['proposals'] = delta['proposals'][skip_n:]
        base = curr_v
    elif curr_v == base + len(delta['proposals']):
        delta['proposals'] = []
        base = curr_v
    if store.version() != base:
        raise ValueError('Delta base_version %s does not match model version %s'
                         % (base, store.version()))
    repairs, problems, entries = [], [], []
    running = base
    for index, proposal in enumerate(delta['proposals']):
        doc = proposal.get('document')
        ops = proposal.get('operations') or []
        if not doc or not isinstance(ops, list):
            raise ValueError('Proposal %d is missing document/operations' % (index + 1))
        resolve_dynamic_ids(store, delta, proposal, repairs)
        ops = proposal.get('operations') or []
        if not ops:
            entries.append({'index': index, 'document': doc, 'skipped': 'no operations'})
            continue
        if len(ops) > 500 or body_size(proposal) > 500000:
            raise ValueError('Proposal %d exceeds the 500-operation / 500 KB limit; split it' % (index + 1))
        before = len(problems)
        visual = resolve_supports(store, proposal, repairs, problems)
        if len(problems) > before:
            entries.append({'index': index, 'document': doc, 'errors': ['support resolution failed']})
            continue
        evidence_ids = [e['id'] for e in store.rows('SELECT id FROM evidence WHERE document_id=?', (doc,))]
        body = build_body(proposal, evidence_ids)
        report = validate(store, {k: body[k] for k in ('summary', 'operations')}, doc, running, visual_ids=visual)
        if commit_changes or report['errors']:
            pkg_dir = out_dir / ('%02d-%s' % (index + 1, doc[4:16]))
            pkg_dir.mkdir(parents=True, exist_ok=True)
            (pkg_dir / 'package.json').write_text(
                json.dumps(body, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
            (pkg_dir / 'validation.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
        if report['errors']:
            problems.extend(['proposal %d (%s): %s' % (index + 1, doc, e) for e in report['errors']])
            entries.append({'index': index, 'document': doc, 'errors': report['errors']})
            continue
        entry = {'index': index, 'document': doc, 'pass': proposal.get('pass_id'),
                 'ops': len(ops), 'warnings': report['warnings']}
        if commit_changes:
            staged = stage(store, doc, body, visual_ids=visual, analysis_dir=str(pkg_dir), expected_version=running)
            result = commit(store, staged['proposal_id'])
            running = result['version']
            entry.update(proposal_id=staged['proposal_id'], version=running)
            (pkg_dir / 'result.json').write_text(json.dumps(entry, indent=2) + '\n', encoding='utf-8')
            print(json.dumps({'document': doc[:12], 'pass': proposal.get('pass_id'),
                              'proposal': staged['proposal_id'], 'version': running, 'ops': len(ops)}))
        entries.append(entry)
    store._batch_shadow = False
    if hasattr(store, '_sync_to_real'):
        store._sync_to_real(force=True)
    return entries, repairs, problems, running


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('delta', help='path to the returned delta JSON')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', action='store_true', help='validate only (default)')
    mode.add_argument('--rehearse', action='store_true', help='apply on a copy of the live DB')
    mode.add_argument('--apply', action='store_true', help='guarded live acceptance (auto-runs --rehearse if needed)')
    parser.add_argument('--live', default=str(ROOT / 'data/plant'))
    parser.add_argument('--workdir', default=str(ROOT / 'output/plant-enrichment/pass06-10-delta'),
                        help='rehearsal/report directory (default output/plant-enrichment/pass06-10-delta)')
    args = parser.parse_args()

    delta, digest = load_delta(args.delta)
    live = Path(args.live)
    workdir = Path(args.workdir)

    if args.apply:
        summary_file = workdir / 'rehearsal-summary.json'
        need_rehearse = True
        if summary_file.exists():
            try:
                summary = json.loads(summary_file.read_text(encoding='utf-8'))
                if summary.get('delta_sha256') == digest and not summary.get('problems'):
                    need_rehearse = False
            except Exception:
                need_rehearse = True
        if need_rehearse:
            target = workdir / 'rehearsal'
            copy_live(live, target)
            r_entries, r_repairs, r_problems, r_running = process(delta, Store(target), target, commit_changes=True, delta_path=args.delta)
            if r_problems:
                raise SystemExit('Rehearsal stopped with problems:\n' + '\n'.join(r_problems))
            summary = {'delta_sha256': digest, 'base_version': delta['base_version'],
                       'final_version': r_running, 'entries': r_entries, 'repairs': r_repairs}
            workdir.mkdir(parents=True, exist_ok=True)
            summary_file.write_text(json.dumps(summary, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
        store = Store(live)
        out_dir = workdir / 'apply'
        out_dir.mkdir(parents=True, exist_ok=True)
        entries, repairs, problems, running = process(delta, store, out_dir, commit_changes=True, delta_path=args.delta)
        if problems:
            raise SystemExit('Apply stopped with problems:\n' + '\n'.join(problems))
        rehearsed_chain = [e.get('version') for e in summary['entries'] if e.get('version')]
        applied_chain = [e.get('version') for e in entries if e.get('version')]
        if applied_chain != rehearsed_chain:
            raise SystemExit('Applied chain %s does not match the rehearsal chain %s'
                             % (applied_chain, rehearsed_chain))
        result = {'applied': True, 'delta_sha256': digest, 'base_version': delta['base_version'],
                  'final_version': running, 'entries': entries, 'repairs': repairs, 'problems': problems}
    elif args.rehearse:
        target = workdir / 'rehearsal'
        copy_live(live, target)
        entries, repairs, problems, running = process(delta, Store(target), target, commit_changes=True, delta_path=args.delta)
        summary = {'delta_sha256': digest, 'base_version': delta['base_version'],
                   'final_version': running, 'entries': entries, 'repairs': repairs}
        (workdir / 'rehearsal-summary.json').write_text(
            json.dumps(summary, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
        result = {'ok': not problems, 'rehearsed': True, **{k: summary[k] for k in ('base_version', 'final_version')},
                  'entries': entries, 'repairs': repairs, 'problems': problems}
    else:
        out_dir = workdir / 'check'
        out_dir.mkdir(parents=True, exist_ok=True)
        check_target = workdir / 'check_db'
        copy_live(live, check_target)
        try:
            entries, repairs, problems, running = process(delta, Store(check_target), out_dir, commit_changes=True, delta_path=args.delta)
        finally:
            shutil.rmtree(check_target, ignore_errors=True)
        result = {'ok': not problems, 'check': True, 'base_version': delta['base_version'],
                  'live_version': running, 'entries': entries, 'repairs': repairs, 'problems': problems}

    (workdir / 'last-run.json').write_text(json.dumps(result, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    print(json.dumps({'ok': not result.get('problems'),
                      'final_version': result.get('final_version', result.get('live_version')),
                      'proposals': len([e for e in result['entries'] if e.get('version') or e.get('errors') is not None or e.get('ops')]),
                      'repairs': len(result.get('repairs') or []),
                      'problems': len(result.get('problems') or [])}))
    if result.get('problems'):
        for problem in result['problems']:
            print('PROBLEM: ' + problem)
        raise SystemExit(1)


if __name__ == '__main__':
    main()
